const DICTIONARIES: Record<LanguageCode, Partial<Dictionary>> = {
  en,
  es,
  fr,
  de,
  hi,
  ja,
};

export type Translator = (key: TranslationKey) => string;

export function translate(language: LanguageCode, key: TranslationKey): string {
  return DICTIONARIES[language][key] ?? en[key];
}

export function createTranslator(language: LanguageCode): Translator {
  return (key) => translate(language, key);
}
